#!/usr/bin/env node
/**
 * validate-sales-rep-demo-data.mjs — STATIC drift guard for the sales-rep DEMO dataset.
 * No network, no env writes, no clock dependence. Run: npm run td:validate:sales-rep-demo
 *
 * This dataset inverts the usual fixture contract: it deliberately carries NO `AGENT-TEST-` prefix,
 * because every string in it is meant to be shown to an audience. That trade buys presentability and
 * sells away the one-line keyword teardown, so the properties that replace it — the hidden
 * `outerId` marker, the `_`-prefixed id ledger, the excluded-product filter — are load-bearing in a
 * way nothing else checks. Each one fails SILENTLY when broken: the seed still runs, the data still
 * appears, and the damage (a fixture SKU on a demo screen, an undeletable dataset, a wave of false
 * STALE reconcile rows) surfaces only in front of the people the demo was for.
 *
 * Checks (exit 1 on any hard problem):
 *  [1] `demoProblems()` — the spec module's own presentation + non-vacuity contract, called rather
 *      than reimplemented, so this guard and the seeder can never disagree about what "wrong" means.
 *  [2] No GUID literal in the spec module, the seeder, or a committed demo data file. Runtime ids
 *      live in `test-data/aliases.<env>.json` only (DV-021), and the demo's ledger likewise: a
 *      ledger committed into the base `aliases.json` would resolve on every environment at once.
 *  [3] Every `sourceFile` in DEMO_DOCUMENTS exists under `test-data/uploads/` or is explicitly
 *      null. A missing file is a WARN, not a failure — the seeder falls back to generated bytes, so
 *      a checkout without the assets still seeds (it just seeds a 562-byte PDF nobody should click).
 *  [4] The demo buyer password is a `{{VAR}}` token in the seeder, never a literal.
 *  [5] `EXCLUDED_PRODUCT_RE` still rejects the fixture products that are LIVE in the catalog right
 *      now, and the seeder still applies it. A regex that rejects correctly but is never called
 *      catches nothing.
 *  [6] The ledger key starts with `_`, which is the only thing keeping `td:reconcile` check [11]
 *      from member-probing every order and file GUID the ledger holds.
 */
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  DEMO_DOCUMENTS, DEMO_ORGS, DEMO_ORDERS, DEMO_TASKS, DEMO_REPS, DEMO_UPLOADS_DIR, DEMO_LEDGER_KEY,
  demoProblems, documentSourceRel, isDemoSafeProduct, EXCLUDED_PRODUCT_RE,
} from './sales-rep-demo-specs.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..', '..');

const problems = [];
const warnings = [];
const fail = (m) => { problems.push(m); console.log(`  ✗ ${m}`); };
const warn = (m) => { warnings.push(m); console.log(`  ⚠ ${m}`); };
const ok = (m) => console.log(`  ✓ ${m}`);

const SPEC_REL = 'scripts/seed-data/sales-rep/sales-rep-demo-specs.mjs';
const SEEDER_REL = 'scripts/seed-data/sales-rep/seed-sales-rep-demo.mjs';
const specSrc = readFileSync(join(ROOT, SPEC_REL), 'utf8');
const seederSrc = readFileSync(join(ROOT, SEEDER_REL), 'utf8');

const GUID_RE = /\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/i;
const GUID_RE_G = new RegExp(GUID_RE.source, 'gi');

console.log('sales-rep DEMO dataset — static drift guard\n');

// [1] the spec module's own contract ----------------------------------------
console.log('[1] demoProblems() — presentation + non-vacuity contract');
const declared = demoProblems();
for (const p of declared) fail(`spec contract: ${p}`);
if (!declared.length) {
  ok(`${DEMO_ORGS.length} org(s), ${DEMO_ORDERS.length} order(s), ${DEMO_DOCUMENTS.length} document(s), `
    + `${DEMO_TASKS.length} task(s), ${DEMO_REPS.length} rep(s) — no AGENT-TEST string, no raw GUID, `
    + 'shared customer present, product pools disjoint by phrase, exactly one pinned document');
}

// [2] no GUID literal in source or committed demo data ------------------------
console.log('\n[2] No runtime GUID in the spec module, the seeder, or committed demo data');
for (const [rel, src] of [[SPEC_REL, specSrc], [SEEDER_REL, seederSrc]]) {
  const hits = [...new Set(src.match(GUID_RE_G) || [])];
  if (hits.length) {
    fail(`${rel} carries GUID literal(s) ${hits.join(', ')} — a platform id is per-environment and `
      + 'belongs in test-data/aliases.<env>.json, never in committed source (DV-021)');
  } else ok(`${rel} — no GUID literal`);
}

// Committed demo data files: any text fixture the dataset owns under test-data/. There are none
// today (the demo declares no CSV/JSON fixture — catalog entities come from live discovery), so
// this scan is a TRIPWIRE for a future one being added with ids baked in.
const demoDataFiles = [];
const scanDirs = ['test-data', join('test-data', 'sales-rep')];
for (const dir of scanDirs) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) continue;
  for (const name of readdirSync(abs)) {
    if (!/sales-rep-demo|demo-sales-rep/i.test(name)) continue;
    if (!/\.(json|csv|txt|md)$/i.test(name)) continue;
    demoDataFiles.push(join(dir, name).replace(/\\/g, '/'));
  }
}
for (const rel of demoDataFiles) {
  const hits = [...new Set(readFileSync(join(ROOT, rel), 'utf8').match(GUID_RE_G) || [])];
  if (hits.length) fail(`committed demo data file ${rel} carries GUID literal(s) ${hits.join(', ')} — move them to test-data/aliases.<env>.json (DV-021)`);
  else ok(`${rel} — no GUID literal`);
}
if (!demoDataFiles.length) ok('no committed demo data file — catalog entities come from live discovery, by design');

// The id ledger is per-environment. In the COMMITTED base registry it would resolve everywhere.
const LEDGER_KEY_IN_SEEDER = DEMO_LEDGER_KEY;
const basePath = join(ROOT, 'test-data', 'aliases.json');
if (LEDGER_KEY_IN_SEEDER && existsSync(basePath)) {
  const base = JSON.parse(readFileSync(basePath, 'utf8'));
  if (LEDGER_KEY_IN_SEEDER in base) {
    fail(`test-data/aliases.json carries the demo ledger "${LEDGER_KEY_IN_SEEDER}" — the ledger holds `
      + 'runtime order/member/file GUIDs for ONE environment and belongs in aliases.<env>.json only');
  } else ok(`committed aliases.json carries no "${LEDGER_KEY_IN_SEEDER}" (the ledger is env-scoped)`);
}

// [3] document source files ---------------------------------------------------
console.log(`\n[3] DEMO_DOCUMENTS sourceFile — present under ${DEMO_UPLOADS_DIR}/ or explicitly null`);
for (const d of DEMO_DOCUMENTS) {
  if (d.sourceFile === null) { ok(`${d.key} — sourceFile null (generated bytes, by declaration)`); continue; }
  if (typeof d.sourceFile !== 'string' || !d.sourceFile.trim()) {
    fail(`${d.key}: sourceFile must be a non-empty string or explicitly null (got ${JSON.stringify(d.sourceFile)}) — `
      + 'an undefined/blank value is indistinguishable from a forgotten one');
    continue;
  }
  const rel = documentSourceRel(d);
  if (existsSync(join(ROOT, rel))) ok(`${d.key} → ${rel}`);
  else {
    warn(`${d.key}: ${rel} is missing — the seeder falls back to generated bytes, so this still seeds, `
      + `but "${d.name}" will open as a one-line placeholder in front of whoever clicks it`);
  }
}

// [4] password is a token, never a literal ------------------------------------
console.log('\n[4] Demo buyer password resolves from a {{VAR}} token');
const pwCalls = [...seederSrc.matchAll(/resolvePassword\(\s*(['"`])([^'"`]*)\1/g)].map((m) => m[2]);
if (!pwCalls.length) {
  fail(`${SEEDER_REL} makes no resolvePassword('{{VAR}}') call — this check cannot pass vacuously: `
    + 'either the buyer accounts lost their credential path, or a literal is being passed some other way');
} else {
  for (const arg of pwCalls) {
    if (/^\{\{[A-Z0-9_]+\}\}$/.test(arg)) ok(`resolvePassword('${arg}') — token, resolved from .env.local at seed time`);
    else fail(`${SEEDER_REL} calls resolvePassword('${arg}') with a LITERAL — committed test-data carries `
      + '{{VAR}} tokens only; real values live in .env.local and the team secret store');
  }
}
for (const m of seederSrc.matchAll(/password\s*[:=]\s*['"]([^'"]+)['"]/gi)) {
  if (!/^\{\{[A-Z0-9_]+\}\}$/.test(m[1])) fail(`${SEEDER_REL} assigns a password literal ("${m[1]}")`);
}
for (const m of specSrc.matchAll(/password\s*[:=]\s*['"]([^'"]+)['"]/gi)) {
  if (!/^\{\{[A-Z0-9_]+\}\}$/.test(m[1])) fail(`${SPEC_REL} assigns a password literal ("${m[1]}")`);
}

// [5] the excluded-product filter still excludes what is live -----------------
console.log('\n[5] EXCLUDED_PRODUCT_RE rejects the fixture products live in the catalog');
// These two are live on virtostart. They are named here deliberately: the point of the check is
// that the regex is confronted with the exact strings it has to stop, not with a synthetic sample
// that happens to match. A line item's name is copied into the order at POST, so discovery is the
// only place this can be caught.
const LIVE_FIXTURE_PRODUCTS = ['AGENT-TEST-Cordless Drill', 'AGENT-TEST-Gloves Winter'];
for (const name of LIVE_FIXTURE_PRODUCTS) {
  const byName = isDemoSafeProduct({ id: 'p1', sku: 'SKU-1', name });
  const bySku = isDemoSafeProduct({ id: 'p1', sku: name, name: 'Innocuous Name' });
  if (byName || bySku) {
    fail(`EXCLUDED_PRODUCT_RE (${EXCLUDED_PRODUCT_RE}) does not reject "${name}" on `
      + `${byName ? 'name' : ''}${byName && bySku ? ' and ' : ''}${bySku ? 'sku' : ''} — this product is live in `
      + 'the catalog and would land on a demo order line, putting the family prefix on the one screen '
      + 'this dataset exists to keep clean');
  } else ok(`"${name}" rejected on both name and sku`);
}
// A filter nothing calls excludes nothing.
if (!/isDemoSafeProduct/.test(seederSrc)) {
  fail(`${SEEDER_REL} no longer references isDemoSafeProduct — the exclusion above is then dead code and `
    + 'discovery will hand fixture products straight into demo order lines');
} else ok('the seeder still applies isDemoSafeProduct at discovery');

// [6] the ledger key stays underscore-prefixed --------------------------------
console.log('\n[6] Ledger key is `_`-prefixed (td:reconcile probe exclusion)');
if (!/DEMO_LEDGER_KEY/.test(seederSrc)) {
  fail(`${SEEDER_REL} no longer imports DEMO_LEDGER_KEY — it has gone back to transcribing the overlay `
    + 'key, which is exactly the silent failure this export removed: rename the key in one file and '
    + 'reconcile check [12] reports "no ledger" forever while the seed still runs green');
} else if (!LEDGER_KEY_IN_SEEDER.startsWith('_')) {
  fail(`LEDGER_KEY = "${LEDGER_KEY_IN_SEEDER}" does not start with "_". selectProbeTargets() in `
    + 'overlay-specs.mjs skips ONLY underscore-prefixed overlay keys, so renaming it re-exposes every '
    + 'order, member and file GUID in the ledger to td:reconcile check [11], which member-probes them '
    + 'and reports each non-member id as STALE — a wave of false failures for ids that were never members.');
} else ok(`LEDGER_KEY = "${LEDGER_KEY_IN_SEEDER}" — skipped by selectProbeTargets()`);

// ---- report ----------------------------------------------------------------
console.log('\n=== sales-rep DEMO dataset validation ===');
console.log(`  hard problems: ${problems.length} | warnings: ${warnings.length}`);
if (problems.length) {
  console.error('\nFAILED — fix the ✗ items above.');
  process.exit(1);
}
console.log('\nsales-rep DEMO test-data OK — presentable, non-vacuous, GUID-free, tearable-down.');
process.exit(0);
