#!/usr/bin/env node
/**
 * Generate the unprompted variant of the run brief.
 *
 *   node measurements/kb-live-2026-09/make-unprompted-brief.mjs
 *
 * Runs 01 and 02 were both TOLD to consult the base. So "agents use the base" was an assumption
 * rather than a result, and it was load-bearing: if an agent reaches for it unprompted a skill is
 * enough, and if it does not, no amount of documentation substitutes for a hook that consults on
 * its behalf. Run 03 settled the first half — it did consult, unprompted, four times — and
 * uncovered the harder half: it consulted only during orientation and never again. See
 * docs/ADOPTION.md and measurements/kb-arrival-2026-09/.
 *
 * GENERATED, NOT COPIED. Two hand-maintained briefs drift, and a drift nobody notices is a change
 * of conditions nobody recorded — which is exactly the failure this whole measurement exists to
 * avoid. Everything except the named block below is byte-identical to RUN-BRIEF.md, and this script
 * fails loudly if that block ever stops matching rather than quietly producing a brief that differs
 * in ways it did not mean to. It has now done that once, for real, when the protocol gained the
 * loop.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const SOURCE = `${HERE}RUN-BRIEF.md`;
const TARGET = `${HERE}RUN-BRIEF-unprompted.md`;

// The one instruction under test: step 2 tells the run to ask the base first. Everything else about
// the protocol stays, so a run that DOES consult is recorded exactly as runs 01-03 were and the
// four are comparable.
const PROMPTED = `**2. Ask the base before you look elsewhere.** When you need to know something about the platform:

\`\`\`
node bin/kb.mjs deliver "the question, in the words you would actually ask it"
\`\`\`

It answers from the derived and experiential planes, or says \`KB MISS\`. Either way the row is now
in the CSV, and the question is now on the base's own books until something is written back about
it. Then go and find out by whatever means the task needs.

**A procedure is a different question and a different verb.** \`deliver\` answers what is TRUE and
cannot reach a flow; \`how "<what you are trying to get done>"\` answers what to DO, in order, and
returns procedures only. Ask it before working out a sequence of steps yourself, and if you do work
one out, \`capture --flow\` records it -- \`--subject\` states the GOAL you reached, not the actions.


Expect an answer rather than a MISS: across three runs the base was asked 23 questions and missed
none of them. That is not the same as being answered. Run 02 asked how a discount is rounded, was
served the derived \`DiscountType\` table, and had to go and read an entry off disk that said what it
needed. **Served is not answered**, and step 3 is where you say which it was.`;

const UNPROMPTED = `**2. There is a knowledge base in this repository.** \`node bin/kb.mjs --help\` explains it. In
short: \`deliver "<question>"\` answers a question about the platform from it or says \`KB MISS\`, and
\`capture\` puts something into it. Anything you ask through \`deliver\` lands in the CSV as a row for
you to close at step 3, and on the base's own books until something is written back about it.

It answers two KINDS of question with two verbs, and neither can reach the other's corpus:
\`deliver\` answers what is TRUE, and \`how "<what you are trying to get done>"\` answers what to DO,
in order. \`capture --flow\` records a procedure, with \`--subject\` stating the GOAL rather than the
actions.

Two things about it that are true whether or not you use it. It rarely misses — across three
previous runs it was asked 23 questions and missed none — and missing is not the same as answering:
one of those runs was served a generated type table for a question that needed something else, and
had to go and find that something else itself. So if you do ask it, step 3 is where you say which
of the two happened.

Use it, or do not, as the work suits you. This paragraph is deliberately not an instruction.`;

const HEADER = `> **This is the unprompted variant of \`RUN-BRIEF.md\`, generated by
> \`make-unprompted-brief.mjs\`.** It is byte-identical to that file except for step 2 of the
> protocol, which states that the base exists instead of telling the run to consult it. Runs 01 and
> 02 were both instructed to; run 03 got this variant and consulted it anyway, four times, all
> during orientation and never again. Do not edit this file — edit \`RUN-BRIEF.md\` and regenerate.

`;

const source = readFileSync(SOURCE, 'utf8');
if (!source.includes(PROMPTED)) {
  console.error('make-unprompted-brief: the step-2 block no longer matches RUN-BRIEF.md.');
  console.error('Refusing to generate: a silent near-miss here would change the run conditions');
  console.error('in ways nobody recorded. Update PROMPTED in this script to the current wording.');
  process.exit(1);
}

const out = source.replace(/^# .*\n/, (title) => `${title}\n${HEADER}`).replace(PROMPTED, UNPROMPTED);
writeFileSync(TARGET, out);
console.log(`written: ${TARGET}`);
console.log(`  ${out.split('\n').length} lines, one block replaced, everything else identical`);
